    private void RegistrarprofesorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RegistrarprofesorActionPerformed
                                              
        try {
            String nombre = Nombre.getText();
            String direccion = Direccion.getText();
            String telefono = Telefono.getText();
            LocalDate fechaNac = LocalDate.parse(FechaNacimiento.getText());
            String cedula = Cedula.getText();
            String area = Area.getText();
            double salarioHora = Double.parseDouble(Salario.getText());
            int horasDictadas = Integer.parseInt(Horas.getText());

            if (nombre.isEmpty() || cedula.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete el nombre y la cédula del profesor.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Profesor prof = new Profesor(nombre, direccion, telefono, fechaNac, cedula, area, salarioHora, horasDictadas);
            miColegio.agregarProfesor(prof);

            JOptionPane.showMessageDialog(this, "¡Profesor registrado con éxito!");
            limpiarCampos();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error en los campos numéricos (Salario u Horas).", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al registrar. Verifique los datos o la fecha (AAAA-MM-DD).", "Error", JOptionPane.ERROR_MESSAGE);
        }
    // TODO add your handling code here:
    }//GEN-LAST:event_RegistrarprofesorActionPerformed

    private void RegistrarestudianteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RegistrarestudianteActionPerformed
                                                
        try {
            String nombre = Nombre.getText();
            String direccion = Direccion.getText();
            String telefono = Telefono.getText();
            LocalDate fechaNac = LocalDate.parse(FechaNacimiento.getText());
            String codigo = Codigo.getText();
            String grado = Grado.getText();

            if (nombre.isEmpty() || codigo.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Complete el nombre y el código del estudiante.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Estudiante est = new Estudiante(nombre, direccion, telefono, fechaNac, codigo, grado);
            miColegio.agregarEstudiante(est);

            JOptionPane.showMessageDialog(this, "¡Estudiante registrado con éxito!");
            limpiarCampos();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al registrar. Verifique el formato de la fecha (AAAA-MM-DD).", "Error", JOptionPane.ERROR_MESSAGE);
        }                                              
    }//GEN-LAST:event_RegistrarestudianteActionPerformed

